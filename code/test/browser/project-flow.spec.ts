import { test, expect } from '@playwright/test';

test('projects isolate files, questions and deletion; confirmed questions open managed diagnosis', async ({page,request})=>{
 const make=async(brand:string)=>(await(await request.post('/api/projects',{data:{brand,industry:'Robotics'}})).json());
 const a=await make('Flow Alpha'),b=await make('Flow Beta');
 await page.goto(`/?project=${a.id}`);
 await page.getByRole('button',{name:'品牌事实',exact:true}).click();
 const form=page.locator('[data-brand-source]');
 await expect(form.locator('input[type=file]')).toBeVisible();
 await form.locator('input[type=file]').setInputFiles({name:'alpha.md',mimeType:'text/markdown',buffer:Buffer.from('Alpha payload: 1.5 kg.')});
 await form.getByRole('button',{name:'导入来源',exact:true}).click();
 await expect(page.getByRole('heading',{name:'alpha.md',exact:true})).toBeVisible();
 await page.getByLabel('当前项目',{exact:true}).selectOption(b.id);
 await page.getByRole('button',{name:'品牌事实',exact:true}).click();
 await expect(page.getByRole('heading',{name:'alpha.md',exact:true})).toHaveCount(0);
 await expect(page.locator('#main')).toContainText('Flow Beta');
 await page.getByRole('button',{name:'问题空间',exact:true}).click();
 await page.getByLabel('问题清单',{exact:true}).fill('Which robotics platforms fit a university lab?');
 await page.getByRole('button',{name:'保存并开始品牌诊断',exact:true}).click();
 await expect(page.getByRole('heading',{name:'运行一轮品牌诊断',exact:true})).toBeVisible();
 await expect(page.locator('#dialog input[name=model]')).toHaveCount(0);
 await expect(page.locator('#dialog input[name=queryIds]')).toHaveCount(1);
 await page.getByRole('button',{name:'取消',exact:true}).click();
 await page.getByRole('button',{name:'项目管理',exact:true}).click();
 page.once('dialog',dialog=>dialog.accept());
 await page.locator(`[data-delete-project="${b.id}"]`).click();
 await expect(page.getByLabel('当前项目',{exact:true})).not.toHaveValue(b.id);
 expect((await request.get(`/api/projects/${b.id}`)).status()).toBe(404);
 expect((await request.get(`/api/projects/${a.id}`)).status()).toBe(200);
 await page.getByRole('button',{name:'项目管理',exact:true}).click();
 await page.locator(`[data-restore-project="${b.id}"]`).click();
 expect((await request.get(`/api/projects/${b.id}`)).status()).toBe(200);
 await page.getByRole('button',{name:'取消',exact:true}).click();
 await page.getByRole('button',{name:'⚙ 服务商设置',exact:true}).click();
 await expect(page.getByRole('heading',{name:'服务商设置',exact:true})).toBeVisible();
 await expect(page.locator('#dialog input[type=password]')).toHaveCount(2);
 await expect(page.locator('#dialog input[name=model],#dialog select[name=provider]')).toHaveCount(0);
 await page.getByRole('button',{name:'取消',exact:true}).click();
 await request.delete(`/api/projects/${a.id}`);await request.delete(`/api/projects/${b.id}`);
});
