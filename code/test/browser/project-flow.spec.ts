import { test, expect } from '@playwright/test';

test('projects isolate files, questions and deletion; confirmed questions open managed diagnosis', async ({page,request})=>{
 const make=async(brand:string)=>(await(await request.post('/api/projects',{data:{brand,industry:'Robotics'}})).json());
 const a=await make('Flow Alpha'),b=await make('Flow Beta');
 await page.goto(`/?project=${a.id}`);
 await page.getByRole('button',{name:'品牌事实',exact:true}).click();
 const form=page.locator('[data-brand-source]');
 await expect(form.locator('input[type=file]')).toBeVisible();
 await form.locator('input[type=file]').setInputFiles({name:'alpha.md',mimeType:'text/markdown',buffer:Buffer.from('Alpha payload: 1.5 kg.')});
 await form.getByRole('button',{name:'导入来源',exact:true}).click();
 await expect(page.getByRole('heading',{name:'alpha.md',exact:true})).toBeVisible();
 await page.getByLabel('当前项目',{exact:true}).selectOption(b.id);
 await page.getByRole('button',{name:'品牌事实',exact:true}).click();
 await expect(page.getByRole('heading',{name:'alpha.md',exact:true})).toHaveCount(0);
 await expect(page.locator('#main')).toContainText('Flow Beta');
 await page.getByRole('button',{name:'问题空间',exact:true}).click();
 await page.getByLabel('问题清单',{exact:true}).fill('Which robotics platforms fit a university lab?');
 await page.getByRole('button',{name:'保存并开始品牌诊断',exact:true}).click();
 await expect(page.getByRole('heading',{name:'运行一轮品牌诊断',exact:true})).toBeVisible();
 await expect(page.locator('#dialog input[name=model]')).toHaveCount(0);
 await expect(page.locator('#dialog input[name=queryIds]')).toHaveCount(1);
 await page.getByRole('button',{name:'取消',exact:true}).click();
 await page.getByRole('button',{name:'项目管理',exact:true}).click();
 page.once('dialog',dialog=>dialog.accept());
 await page.locator(`[data-delete-project="${b.id}"]`).click();
 await expect(page.getByLabel('当前项目',{exact:true})).not.toHaveValue(b.id);
 expect((await request.get(`/api/projects/${b.id}`)).status()).toBe(404);
 expect((await request.get(`/api/projects/${a.id}`)).status()).toBe(200);
 await page.getByRole('button',{name:'项目管理',exact:true}).click();
 await page.locator(`[data-restore-project="${b.id}"]`).click();
 expect((await request.get(`/api/projects/${b.id}`)).status()).toBe(200);
 await page.getByRole('button',{name:'取消',exact:true}).click();
 await page.getByRole('button',{name:'⚙ 服务商设置',exact:true}).click();
 await expect(page.getByRole('heading',{name:'服务商设置',exact:true})).toBeVisible();
 await expect(page.locator('#dialog input[type=password]')).toHaveCount(2);
 await expect(page.locator('#dialog input[name=model],#dialog select[name=provider]')).toHaveCount(0);
 await page.getByRole('button',{name:'取消',exact:true}).click();
 await request.delete(`/api/projects/${a.id}`);await request.delete(`/api/projects/${b.id}`);
});

test('saved diagnosis spaces survive reload, separate question snapshots and reopen their run progress', async ({page,request})=>{
 const {Store}=await import('../../src/citekeel/storage.js');
 const {createRun}=await import('../../src/citekeel/engine.js');
 const store=new Store('data/browser-tests');
 const project=await(await request.post('/api/projects',{data:{brand:'Space fixture',industry:'Robotics'}})).json();
 await page.goto(`/?project=${project.id}`);
 await page.getByRole('button',{name:'问题空间',exact:true}).click();
 await page.getByLabel('问题清单',{exact:true}).fill('Which platform fits a research lab?');
 await page.getByRole('button',{name:'保存并确认问题',exact:true}).click();
 await expect(page.locator('[data-space] option:checked')).toContainText('问题集');
 const firstSpace=await page.locator('[data-space]').inputValue();
 await page.getByRole('button',{name:'在此空间开始测试',exact:true}).click();
 for (const item of await page.locator('input[name=targetIds]').all()) await item.uncheck();
 await page.locator('input[name=targetIds][value=qwen]').check();
 await page.getByRole('button',{name:'保存选择，稍后测试',exact:true}).click();
 await expect(page.locator('#dialog')).not.toBeVisible();
 await page.reload();
 await expect(page.locator('[data-space]')).toHaveValue(firstSpace);
 await page.getByRole('button',{name:'在此空间开始测试',exact:true}).click();
 await expect(page.locator('input[name=targetIds]:checked')).toHaveCount(1);
 await expect(page.locator('input[name=targetIds][value=qwen]')).toBeChecked();
 await page.getByRole('button',{name:'取消',exact:true}).click();
 await page.getByRole('button',{name:'问题空间',exact:true}).click();
 await expect(page.getByLabel('问题清单',{exact:true})).toHaveValue('Which platform fits a research lab?');
 const resave=page.waitForResponse(r=>r.url().endsWith(`/api/projects/${project.id}`)&&r.request().method()==='GET');
 await page.getByRole('button',{name:'保存并确认问题',exact:true}).click();
 await resave;
 await expect(page.getByLabel('问题清单',{exact:true})).toHaveValue('Which platform fits a research lab?');
 await expect(page.locator('[data-space]')).toHaveValue(firstSpace);
 expect((await(await request.get(`/api/projects/${project.id}/diagnosis-spaces`)).json()).length).toBe(1);
 await page.getByLabel('问题清单',{exact:true}).fill('Which mobile robot fits a classroom?');
 await page.getByRole('button',{name:'保存并确认问题',exact:true}).click();
 await expect(page.locator('[data-space]')).not.toHaveValue(firstSpace);
 const secondSpace=await page.locator('[data-space]').inputValue();
 await page.locator('[data-space]').selectOption(firstSpace);
 await expect(page.getByLabel('问题清单',{exact:true})).toHaveValue('Which platform fits a research lab?');
 const saved=await(await request.get(`/api/projects/${project.id}`)).json();
 const space=saved.diagnosisSpaces.find((s:any)=>s.id===firstSpace);
 const run=createRun({...saved,queries:space.queries,queryVersion:space.queryVersion},'live');run.spaceId=firstSpace;run.status='running';
 run.steps[0].status='completed';run.steps[1].status='completed';run.steps[2].status='running';
 run.measurementUnits=[{id:'unit-1',queryId:space.queries[0].id,question:space.queries[0].text,targetId:'qwen',platform:'Qwen',preferredChannel:'api',status:'planned',attempts:[]}];
 await store.save('runs',run);
 await page.goto(`/?project=${project.id}&space=${firstSpace}&run=${run.id}`);
 await expect(page.getByRole('heading',{name:'品牌诊断进行中',exact:true})).toBeVisible();
 await expect(page.getByRole('progressbar',{name:'诊断执行进度',exact:true})).toHaveAttribute('value','25');
 await expect(page.locator('.da-metrics')).toHaveCount(0);
 await expect(page.getByRole('link',{name:'HTML 报告',exact:true})).toHaveCount(0);
 await page.screenshot({path:'/tmp/opengeo-space-running.png',fullPage:true});
 await page.reload();
 await expect(page.getByRole('heading',{name:'品牌诊断进行中',exact:true})).toBeVisible();
 run.status='needs_review';run.finishedAt=new Date().toISOString();run.measurementUnits[0].status='failed';run.steps.forEach(s=>s.status='completed');
 await store.save('runs',run);
 await expect(page.getByRole('heading',{name:'执行已结束，有待处理项',exact:true})).toBeVisible();
 await expect(page.locator('.da-metrics')).toBeVisible();
 await expect(page.locator('[data-space-run]')).toHaveValue(run.id);
 await page.screenshot({path:'/tmp/opengeo-space-finished.png',fullPage:true});
 await page.setViewportSize({width:375,height:812});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.locator('[data-space]').selectOption(secondSpace);
 await expect(page.locator('[data-space-run]')).toHaveValue('');
 await expect(page.locator('.execution-panel')).toHaveCount(0);
 await page.locator('[data-space]').selectOption(firstSpace);
 await expect(page.getByRole('heading',{name:'执行已结束，有待处理项',exact:true})).toBeVisible();
 await page.reload();
 await expect(page.locator('[data-space-run]')).toHaveValue(run.id);
 await request.delete(`/api/projects/${project.id}`);
});
